import assert from "node:assert/strict";
import { planSwipeRuntime } from "../src/tinder-swipe-runtime-gates.ts";
import { DEFAULT_SMART_AUTO_SWIPE_CONFIG, emptySmartSwipeDay, beginSmartSwipeSession, tinderAccountDayKey } from "../src/tinder-smart-auto-swipe-policy.ts";
const config = { ...DEFAULT_SMART_AUTO_SWIPE_CONFIG, enabled: true };
const now = Date.parse("2026-10-16T10:00:00Z");
const tz = "Europe/Paris";
const day = tinderAccountDayKey(now, tz);
const progress = beginSmartSwipeSession(config, emptySmartSwipeDay(day), now, tz, () => 0);
assert.ok(progress);
const evidence = { version: 1, route: "recs", status: "observed", likeControls: 1, passControls: 1, superLikeControls: 2, rewindControls: 1, rewindEnabled: true, actionConfirmed: false };
const availability = { newMatchesAvailable: true, activeChatsAvailable: true, activeConversationInProgress: false, mandatoryStop: false };
const ready = planSwipeRuntime(config, progress, evidence, now, tz, availability);
assert.equal(ready.activity, "swipe");
assert.equal(ready.swipeStatus, "ready");
assert.equal(ready.canExecuteLiveLike, false);
assert.equal(planSwipeRuntime(config, progress, { ...evidence, likeControls: 2 }, now, tz, availability).activity, "new-match");
assert.equal(planSwipeRuntime(config, progress, { ...evidence, route: "other" }, now, tz, availability).swipeStatus, "wrong-route");
assert.equal(planSwipeRuntime(config, progress, evidence, now, tz, { ...availability, activeConversationInProgress: true }).activity, "active-chat");
assert.equal(planSwipeRuntime(config, progress, evidence, now, tz, { ...availability, mandatoryStop: true }).activity, null);
assert.equal(planSwipeRuntime(config, { ...progress, rightSwipesReserved: 1 }, evidence, now, tz, availability).swipeStatus, "unresolved-attempt");
console.log("Swipe runtime coordinator gates passed.");
