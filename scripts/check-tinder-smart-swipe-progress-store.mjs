import assert from "node:assert/strict";
import { readSmartSwipeProgress, validSmartSwipeProgress } from "../src/tinder-smart-swipe-progress-store.ts";
import { emptySmartSwipeDay } from "../src/tinder-smart-auto-swipe-policy.ts";
const now = Date.parse("2026-10-16T11:00:00Z");
const tz = "Europe/Paris";
const initial = readSmartSwipeProgress(undefined, now, tz);
assert.equal(initial.ok, true);
assert.equal(initial.progress.startedSessions, 0);
assert.equal(initial.needsSave, true);
const current = { ...emptySmartSwipeDay("2026-10-16"), rightSwipesReserved: 1 };
assert.equal(validSmartSwipeProgress(current), true);
assert.equal(readSmartSwipeProgress(current, now, tz).progress.rightSwipesReserved, 1);
assert.equal(readSmartSwipeProgress({ ...current, dayKey: "2026-10-15" }, now, tz).reason, "unresolved-previous-day");
assert.equal(readSmartSwipeProgress({ ...current, rightSwipesReserved: 0, dayKey: "2026-10-15" }, now, tz).progress.startedSessions, 0);
assert.equal(readSmartSwipeProgress({ ...current, rightSwipesReserved: -1 }, now, tz).reason, "corrupt-progress");
assert.equal(readSmartSwipeProgress({ ...current, session: { durationMs: -1 } }, now, tz).reason, "corrupt-progress");
assert.equal(readSmartSwipeProgress({ ...current, dayKey: "garbage" }, now, tz).reason, "corrupt-progress");
assert.equal(readSmartSwipeProgress(undefined, now, "Invalid/Zone").reason, "invalid-account-time");
console.log("Smart Swipe per-account progress validation passed.");
